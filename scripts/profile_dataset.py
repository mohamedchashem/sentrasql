"""Profile the raw dataset found in ``data/raw`` and write a Markdown report.

The dataset file is located automatically by scanning ``data/raw`` for
``.csv`` / ``.xlsx`` files (no hardcoded filename). The raw data is only
inspected -- no cleaning or transformation is applied. The resulting profile
is written to ``reports/data_profile.md``.
"""

from __future__ import annotations

import logging
import sys
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parent.parent
RAW_DIR = PROJECT_ROOT / "data" / "raw"
REPORT_DIR = PROJECT_ROOT / "reports"
REPORT_PATH = REPORT_DIR / "data_profile.md"

DATA_EXTENSIONS = {".csv", ".xlsx"}
PREVIEW_ROWS = 5
LOW_CARDINALITY_LIMIT = 50
CELL_DISPLAY_LIMIT = 120

logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")
logger = logging.getLogger("profile_dataset")


def _md(value: object) -> str:
    """Render a scalar value as a safe, single-line Markdown table cell."""
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return ""
    text = str(value)
    text = text.replace("\\", "\\\\").replace("|", "\\|")
    text = text.replace("\r", " ").replace("\n", " ")
    if len(text) > CELL_DISPLAY_LIMIT:
        text = text[: CELL_DISPLAY_LIMIT - 3] + "..."
    return text


def _df_to_md_table(frame: pd.DataFrame) -> str:
    """Render a DataFrame as a Markdown table."""
    if frame.empty:
        return "_No rows to display._"
    lines = ["| " + " | ".join(_md(column) for column in frame.columns) + " |"]
    lines.append("| " + " | ".join(["---"] * frame.shape[1]) + " |")
    for _, row in frame.iterrows():
        lines.append("| " + " | ".join(_md(value) for value in row) + " |")
    return "\n".join(lines)


def _counts_to_md_table(counts: pd.Series) -> str:
    """Render a value-counts Series as a Markdown table."""
    lines = ["| Value | Count |", "| --- | ---: |"]
    for value, count in counts.items():
        lines.append(f"| {_md(value)} | {count:,} |")
    return "\n".join(lines)

def find_dataset_file() -> Path:
    """Return the first ``.csv`` / ``.xlsx`` file in ``data/raw``."""
    candidates = sorted(
        path
        for path in RAW_DIR.iterdir()
        if path.is_file() and path.suffix.lower() in DATA_EXTENSIONS
    )
    if not candidates:
        raise FileNotFoundError(
            f"No .csv or .xlsx dataset found in '{RAW_DIR}'. "
            "Add a dataset file there and run the script again."
        )
    if len(candidates) > 1:
        logger.warning(
            "Multiple datasets found in '%s' (%s); profiling only '%s'.",
            RAW_DIR,
            ", ".join(path.name for path in candidates),
            candidates[0].name,
        )
    return candidates[0]


def load_dataset(path: Path) -> tuple[pd.DataFrame, str]:
    """Load the dataset and return ``(dataframe, encoding_label)``."""
    suffix = path.suffix.lower()
    if suffix == ".csv":
        try:
            df = pd.read_csv(path, encoding="utf-8")
            encoding = "utf-8"
        except UnicodeDecodeError:
            logger.warning(
                "UTF-8 decoding failed for '%s'; falling back to latin1.", path.name
            )
            df = pd.read_csv(path, encoding="latin1")
            encoding = "latin1"
        logger.info("Read CSV '%s' using encoding: %s", path.name, encoding)
        return df, encoding
    if suffix == ".xlsx":
        logger.info("Reading XLSX '%s' with pandas Excel support.", path.name)
        return pd.read_excel(path), "n/a (xlsx)"
    raise ValueError(f"Unsupported dataset format: '{suffix}'")


def build_report(df: pd.DataFrame, dataset_path: Path, encoding: str) -> str:
    """Assemble the full Markdown profile report as a single string."""
    n_rows, n_cols = df.shape
    null_counts = df.isna().sum()
    sections: list[str] = []

    # Title block.
    sections.append(f"# Data Profile: {dataset_path.name}")
    sections.append("_Automatically generated by `scripts/profile_dataset.py`._")


    # 1. Overview
    sections.append(
        "\n".join(
            [
                "## 1. Overview",
                "",
                "| Metric | Value |",
                "| --- | --- |",
                f"| Source file | `{dataset_path.as_posix()}` |",
                f"| File format | {dataset_path.suffix.lstrip('.').upper()} |",
                f"| Encoding used | {encoding} |",
                f"| Row count | {n_rows:,} |",
                f"| Column count | {n_cols} |",
            ]
        )
    )

    # 2. Columns and data types.
    type_rows = ["| # | Column | Data type |", "| ---: | --- | --- |"]
    for index, (name, dtype) in enumerate(df.dtypes.items(), start=1):
        type_rows.append(f"| {index} | {_md(name)} | {dtype} |")
    sections.append("## 2. Columns and Data Types\n\n" + "\n".join(type_rows))

    # 3. Preview of the first rows.
    preview_rows = min(PREVIEW_ROWS, n_rows)
    sections.append(
        f"## 3. Preview (first {preview_rows} row{'s' if preview_rows != 1 else ''})\n\n"
        + _df_to_md_table(df.head(PREVIEW_ROWS))
    )

    # 4. Null values per column.
    null_rows = ["| Column | Null count | Null % |", "| --- | ---: | ---: |"]
    for name in df.columns:
        count = int(null_counts[name])
        percent = (100.0 * count / n_rows) if n_rows else 0.0
        null_rows.append(f"| {_md(name)} | {count:,} | {percent:.2f}% |")
    sections.append("## 4. Null Values per Column\n\n" + "\n".join(null_rows))

    # 5. Date-like columns (name contains "date", case-insensitive): min / max.
    date_columns = [col for col in df.columns if "date" in str(col).lower()]
    sections.append("## 5. Date Columns (min / max)")
    if not date_columns:
        sections.append(
            '_No column names containing "date" (case-insensitive) were found._'
        )
    else:
        date_rows = ["| Column | Min | Max |", "| --- | --- | --- |"]
        for col in date_columns:
            if not df[col].notna().any():
                date_rows.append(
                    f"| {_md(col)} | _no non-null values_ | _no non-null values_ |"
                )
            else:
                date_rows.append(
                    f"| {_md(col)} | {_md(df[col].min())} | {_md(df[col].max())} |"
                )
        sections.append("\n".join(date_rows))

    # 6. Low-cardinality columns (< 50 unique values) with value counts.
    sections.append(
        f"## 6. Low-Cardinality Columns (< {LOW_CARDINALITY_LIMIT} unique values)"
    )
    low_cardinality = [
        col
        for col in df.columns
        if df[col].nunique(dropna=True) < LOW_CARDINALITY_LIMIT
    ]
    if not low_cardinality:
        sections.append(
            f"_None: every column has at least {LOW_CARDINALITY_LIMIT} unique values._"
        )
    else:
        low_sections: list[str] = []
        for col in low_cardinality:
            counts = df[col].value_counts()
            n_unique = int(counts.size)
            low_sections.append(f"### {_md(col)} ({n_unique} unique non-null values)")
            low_sections.append(
                _counts_to_md_table(counts)
                if not counts.empty
                else "_No non-null values._"
            )
        sections.append("\n\n".join(low_sections))

    return "\n\n".join(sections) + "\n"


def main() -> None:
    """Locate the dataset, profile it, and write ``reports/data_profile.md``."""
    dataset_path = find_dataset_file()
    logger.info("Profiling dataset: %s", dataset_path.name)

    df, encoding = load_dataset(dataset_path)
    report = build_report(df, dataset_path, encoding)

    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(report, encoding="utf-8")
    print(f"Dataset profile report written to: {REPORT_PATH}")


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")
    except Exception:
        pass
    main()

